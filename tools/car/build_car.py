"""
NIGHTSHIFT: builds the player's car from nothing but this code.

  "C:/Program Files/Blender Foundation/Blender 4.3/blender.exe" --background --factory-startup \
      --python tools/car/build_car.py -- [options]

Options (after the "--"):
  --out <file.glb>     write the raw model (default: tools/car/out/player_car.raw.glb)
  --meta <file.json>   write the measurements the game needs (default: next to --out, .meta.json)
  --only a,b           build only these modules: body, interior, wheels, details, bay, lamps (default: all)
  --render <dir>       render previews into this directory after the build
  --views a,b,c        which views (see lib/render.py VIEWS; default front34,rear34,side)
  --mode beauty|zebra|clay   (default beauty)        --res 1280x720      --samples 40
  --device CPU|GPU     Cycles device for the previews (default CPU)
  --prefix name        file name prefix of the previews (default "car")
  --blend <file>       also save the scene as a .blend (for looking at it by hand)
  --no-export          skip the glTF export

No file is read except the modules next to this script: no downloaded model, no part library.
The raw .glb is then packed for the game by tools/car/pack.mjs.
"""
import importlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import bpy  # noqa: E402
from lib import materials, render, spec, util  # noqa: E402

MODULES = ['body', 'interior', 'wheels', 'details', 'bay', 'lamps']


def parse_args():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    out = {}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a.startswith('--'):
            k = a[2:]
            if i + 1 < len(argv) and not argv[i + 1].startswith('--'):
                out[k] = argv[i + 1]
                i += 1
            else:
                out[k] = True
        i += 1
    return out


class Ctx:
    """What every module gets: the collection to put objects in, the root, materials, shared notes."""

    def __init__(self, col):
        self.col = col
        self.spec = spec
        self.root = None       # empty "PlayerCar": every part is a child of it
        self.body = None       # the "Body" object (set by lib/body.py); children of it move with the body
        self.anchors = {}      # name -> (x, y, z) in Blender space, filled by the modules
        self.meta = {}         # free-form measurements a module wants in the .meta.json
        self.only = None

    def mat(self, name):
        return materials.get(name)

    def body_parent(self):
        """Parent for things that are rigidly part of the body (interior, lamps, trim)."""
        return self.body if self.body is not None else self.root


def part_objects(ctx, name):
    """A named part and everything parented under it."""
    top = bpy.data.objects.get(name)
    if top is None:
        return []
    out = [top]
    stack = [top]
    while stack:
        o = stack.pop()
        for c in o.children:
            out.append(c)
            stack.append(c)
    return out


def measure(ctx):
    S = spec
    meshes = [o for o in ctx.col.all_objects if o.type == 'MESH']
    body_like = [o for o in meshes if not o.name.startswith('Mirror') and not any(p.name.startswith('Mirror') for p in _ancestors(o))]
    lo, hi = util.bounds(body_like) if body_like else ((0, 0, 0), (0, 0, 0))
    lo_all, hi_all = util.bounds(meshes) if meshes else (lo, hi)
    hubs = {k: (v[0], v[1], S.HUB_Z) for k, v in S.WHEELS.items()}
    anchors = dict(default_anchors())
    anchors.update(ctx.anchors)
    steer = ctx.meta.get('steering') or {'pivot': S.STEER_CENTRE, 'axis': _steer_axis()}
    parts = {}
    for name in ('MirrorL', 'MirrorR'):
        o = bpy.data.objects.get(name)
        if o is not None:
            parts[name] = {'pivot': util.to_gltf(o.matrix_world.translation)}
    g = util.to_gltf
    meta = {
        'version': 2,
        'source': 'NIGHTSHIFT player car, generated by tools/car/build_car.py (Blender, no external model)',
        'space': 'Y up, metres, car faces -Z, origin = centre of wheelbase on the ground',
        'wheels': [{'key': k, 'hub': g(hubs[k]), 'front': S.WHEELS[k][3]} for k in ('FL', 'FR', 'RL', 'RR')],
        'wheelRadius': S.WHEEL_R,
        'dims': {
            'length': round(hi[1] - lo[1], 4),
            'width': round(hi[0] - lo[0], 4),
            'widthMirrors': round(hi_all[0] - lo_all[0], 4),
            'height': round(hi[2], 4),
            'wheelBase': round(S.WHEELBASE, 4),
            'trackFront': S.TRACK_F,
            'trackRear': S.TRACK_R,
            'wheelRadius': S.WHEEL_R,
            'wheelWidth': S.TYRE_W_R,
            'frontAxle': S.FRONT_AXLE_Y,
            'rearAxle': -S.REAR_AXLE_Y,
            'frontOverhang': round(hi[1] - S.FRONT_AXLE_Y, 4),
            'rearOverhang': round(S.REAR_AXLE_Y - lo[1], 4),
        },
        'steering': {'pivot': g(steer['pivot']), 'axis': g(steer['axis'])},
        'anchors': {k: g(v) for k, v in anchors.items()},
        'parts': parts,
        'triangles': {name: util.tri_count(part_objects(ctx, name)) for name in spec.PART_NAMES},
    }
    meta['triangles']['total'] = util.tri_count(meshes)
    meta.update({k: v for k, v in ctx.meta.items() if k not in ('steering',)})
    return meta


def _ancestors(o):
    p = o.parent
    while p is not None:
        yield p
        p = p.parent


def _steer_axis():
    import math
    t = math.radians(spec.STEER_TILT_DEG)
    return (0.0, -math.cos(t), math.sin(t))


def default_anchors():
    S = spec
    return {
        'headlightL': (-0.66, S.NOSE_Y - 0.30, 0.62),
        'headlightR': (0.66, S.NOSE_Y - 0.30, 0.62),
        'taillightL': (-0.55, S.TAIL_Y + 0.06, 0.82),
        'taillightR': (0.55, S.TAIL_Y + 0.06, 0.82),
        'exhaustL': (-0.30, S.TAIL_Y - 0.01, 0.42),
        'exhaustR': (0.30, S.TAIL_Y - 0.01, 0.42),
        'hoodCam': (0.0, S.FRONT_AXLE_Y + 0.05, 0.92),
    }


def place_mirrors(ctx):
    """The mirrors are modelled at spec.MIRROR_FOOT; the body says where its door shoulder really is."""
    foot = ctx.meta.pop('mirror_foot', None)
    if foot is None:
        return
    for name, sign in (('MirrorR', 1), ('MirrorL', -1)):
        o = bpy.data.objects.get(name)
        if o is None:
            continue
        bpy.context.view_layer.update()
        mw = o.matrix_world.copy()
        mw.translation = (sign * foot[0], foot[1], foot[2])
        o.matrix_world = mw


def finish_meshes(ctx):
    """Every mesh leaves with one UV set: a box projection in metres (the game tiles its detail textures over it);
    the helper layers of the build are dropped."""
    from lib import body
    for o in ctx.col.all_objects:
        if o.type == 'MESH':
            body.box_uv(o)
            body.clean(o)


def export_glb(ctx, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    objs = list(ctx.col.all_objects)
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = ctx.root
    kw = dict(
        filepath=path, export_format='GLB', use_selection=True, export_apply=True, export_yup=True,
        export_extras=True, export_materials='EXPORT', export_normals=True, export_texcoords=True,
        export_tangents=False, export_cameras=False, export_lights=False, export_animations=False,
        export_skins=False, export_morph=False,
    )
    try:
        bpy.ops.export_scene.gltf(export_vertex_color='ACTIVE', export_all_vertex_colors=False, **kw)
    except TypeError:
        bpy.ops.export_scene.gltf(**kw)
    return os.path.getsize(path)


def main():
    util.low_priority()
    args = parse_args()
    t0 = time.time()
    util.reset_scene()
    materials.reset()
    ctx = Ctx(util.collection('Car'))
    ctx.root = util.empty('PlayerCar', col=ctx.col, size=0.3)
    only = [m.strip() for m in str(args['only']).split(',')] if 'only' in args else MODULES
    ctx.only = only
    for name in MODULES:
        if name not in only:
            continue
        t = time.time()
        mod = importlib.import_module('lib.' + name)
        mod.build(ctx)
        print(f'[car] {name}: built in {time.time() - t:.1f} s')
    place_mirrors(ctx)
    bpy.context.view_layer.update()
    finish_meshes(ctx)

    meta = measure(ctx)
    print('[car] triangles:', json.dumps(meta['triangles']))
    print('[car] dims:', json.dumps(meta['dims']))

    out = args.get('out') or os.path.join(HERE, 'out', 'player_car.raw.glb')
    if 'no-export' not in args:
        size = export_glb(ctx, out)
        meta_path = args.get('meta') or (os.path.splitext(out)[0].replace('.raw', '') + '.meta.json')
        with open(meta_path, 'w', encoding='utf-8') as f:
            json.dump(meta, f, indent=1)
        print(f'[car] wrote {out} ({size / 1e6:.2f} MB) and {meta_path}')
    if 'blend' in args:
        bpy.ops.wm.save_as_mainfile(filepath=os.path.abspath(args['blend']))
    if 'render' in args:
        views = [v.strip() for v in str(args.get('views', 'front34,rear34,side')).split(',')]
        res = tuple(int(v) for v in str(args.get('res', '1280x720')).split('x'))
        mode = str(args.get('mode', 'beauty'))
        render.setup_studio(floor=True)
        render.render_views(os.path.abspath(args['render']), views, mode=mode, res=res,
                            samples=int(args.get('samples', 40)), prefix=str(args.get('prefix', 'car')),
                            device=str(args.get('device', 'CPU')))
    print(f'[car] done in {time.time() - t0:.1f} s')


if __name__ == '__main__':
    main()
